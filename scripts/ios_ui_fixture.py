@contextmanager
def fixture_directory(repo):
    """Retain only an explicitly requested, new, private directory outside the repo."""
    requested = os.environ.get("IOS_UI_FIXTURE_PATH")
    if requested is None:
        with tempfile.TemporaryDirectory(prefix="holon-ios-ui-") as temporary:
            yield pathlib.Path(temporary)
        return
    path = pathlib.Path(requested)
    if not requested or not path.is_absolute() or path == pathlib.Path("/") or ".." in path.parts:
        raise RuntimeError("IOS_UI_FIXTURE_PATH must be an unused non-root absolute path")
    if os.path.lexists(path):
        raise RuntimeError("IOS_UI_FIXTURE_PATH already exists")
    parent = path.parent.resolve(strict=True)
    root = parent / path.name
    if root.is_relative_to(pathlib.Path(repo).resolve()):
        raise RuntimeError("IOS_UI_FIXTURE_PATH must be outside the repository")
    # A linked checkout must not retain raw databases in the canonical checkout
    # or any sibling worktree, including through a symlinked parent.
    worktrees = subprocess.run(["git", "-C", str(repo), "worktree", "list", "--porcelain", "-z"],
                              check=True, capture_output=True, text=True).stdout
    roots = [pathlib.Path(entry.removeprefix("worktree ")).resolve()
             for entry in worktrees.split("\0") if entry.startswith("worktree ")]
    if not roots or any(root.is_relative_to(checkout) for checkout in roots):
        raise RuntimeError("IOS_UI_FIXTURE_PATH must be outside all related Git checkouts")
    # mkdir is exclusive: never reuse, chmod or delete an existing evidence path.
    root.mkdir(mode=0o700)
    previous_umask = os.umask(0o077)
    print(f"私有本地验收材料保留目录：{root}（原始数据库可能含隔离测试认证记录，禁止公开）", flush=True)
    try:
        yield root
    finally:
        os.umask(previous_umask)
        print(f"验收材料目录已保留：{root}", flush=True)


def write_fixture_bytes(evidence, name, data):
    if evidence is None:
        return None
    evidence.mkdir(mode=0o700, exist_ok=True)
    with os.fdopen(os.open(evidence / name, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "wb") as stream:
        stream.write(data)
    return {"path": name, "sha256": hashlib.sha256(data).hexdigest()}


def write_fixture_json(evidence, name, value):
    return write_fixture_bytes(evidence, name, json.dumps(
        value, ensure_ascii=False, indent=2).encode("utf-8"))


def fixture_prompt_kind(request):
    """Only recognize payloads generated by the isolated native acceptance probes."""
    text = request.get("text", "")
    if "IOS_LOST_RESPONSE_SEND" in text:
        return "app-lost-response"
    if "IOS_SHARED_TEXT" in text:
        return "share-text"
    if text == "https://example.test/holon-share":
        return "share-url"
    for attachment in request.get("attachments", []):
        data = base64.b64decode(attachment.get("data_base64", ""), validate=True)
        if attachment.get("kind") == "file" and data == b"IOS_SHARED_FILE_BYTES":
            return "share-file"
        if (attachment.get("kind") == "image" and data.startswith(b"\x89PNG\r\n\x1a\n")
                and len(data) >= 24 and struct.unpack(">II", data[16:24]) == (16, 16)):
            return "share-image"
    return None


def record_fixture_prompt(evidence, number, case, path, body, data, status, delivered):
    request, receipt = json.loads(body), json.loads(data)
    # Exact bodies, not headers, tickets, sessions or control traffic. Fail closed
    # on unexpected fields rather than silently redacting an alleged raw artifact.
    if (set(request) - {"text", "attachments", "client_request_id", "work_item_id"}
            or set(receipt) - {"ok", "agent_id", "message_id", "disposition"}
            or any(set(item) - {"kind", "name", "media_type", "data_base64"}
                   for item in request.get("attachments", []))):
        raise RuntimeError("Unexpected fields in fixture prompt evidence")
    stem = f"prompt-{number:04}"
    record = {"source": "real daemon HTTP prompt response", "case": case,
              "kind": fixture_prompt_kind(request), "path": path, "status": status,
              "delivered": delivered, "request": request, "receipt": receipt,
              "request_body": write_fixture_bytes(evidence, stem + "-request.json", body),
              "receipt_body": write_fixture_bytes(evidence, stem + "-receipt.json", data)}
    write_fixture_json(evidence, stem + ".json", record)
    return record


def seed_fixture_history(local, agent, history_seed_active, count=25, marker_prefix="IOS_HISTORY"):
    # Keep short seed replies scoped to preparation, never to later UI prompts.
    history_seed_active.set()
    try:
        for number in range(count):
            marker = f"{marker_prefix}_{number:03}"
            local("POST", f"/agents/{agent}/enqueue", {"text": marker})
            for attempt in range(200):
                history = local("GET", f"/agents/{agent}/conversation")
                if any(marker in json.dumps(turn) and turn.get("brief_ids")
                       for turn in history.get("turns", [])):
                    break
                time.sleep(.1)
            else:
                raise RuntimeError("history fixture turn did not finish")
    finally:
        history_seed_active.clear()


def conversation_inputs(conversation):
    # History includes running turns. Overlay active membership by turn identity,
    # never by message ID: duplicate logical inputs must still fail validation.
    turns = {turn["turn_id"]: turn for turn in conversation["turns"]}
    turns.update((turn["turn_id"], turn) for turn in conversation.get("active_turns", []))
    return [value for turn in turns.values() for value in turn.get("inputs", [])] + conversation.get("pending_inputs", [])


def direct_share_evidence(root, workspace, agent, prompts, inputs, local):
    """Join each native request to one real input/message and its own attachment."""
    kinds = ("share-text", "share-url", "share-image", "share-file")
    if {record["kind"] for record in prompts} != set(kinds):
        raise RuntimeError("Direct-share evidence must cover four request kinds")
    chains, files, seen_requests, seen_messages = [], [], set(), set()
    for kind in kinds:
        attempts = [record for record in prompts if record["kind"] == kind]
        request = attempts[0]["request"]
        try:
            request_id = str(uuid.UUID(request["client_request_id"]))
        except (ValueError, KeyError, TypeError, AttributeError) as error:
            raise RuntimeError("Direct-share evidence lacks a native request UUID") from error
        message_id = attempts[0]["receipt"].get("message_id")
        if not message_id or request_id in seen_requests or message_id in seen_messages:
            raise RuntimeError("Direct-share kinds must have independent UUIDs and messages")
        seen_requests.add(request_id)
        seen_messages.add(message_id)
        for index, attempt in enumerate(attempts):
            receipt = attempt["receipt"]
            if (attempt["request"] != request or fixture_prompt_kind(request) != kind
                    or attempt["case"] != "testDirectAgentShareWorkflow"
                    or not attempt["path"].endswith(f"/agents/{agent}/prompt")
                    or attempt["status"] != 200 or receipt.get("ok") is not True
                    or receipt.get("agent_id") != agent or receipt.get("message_id") != message_id
                    or receipt.get("disposition") != ("accepted" if index == 0 else "duplicate")):
                raise RuntimeError("Direct-share retry changed request, identity or receipt")
        if not any(attempt["delivered"] for attempt in attempts):
            raise RuntimeError("Direct-share receipt was never delivered")
        matching = [value for value in inputs if value.get("message_id") == message_id]
        if len(matching) != 1:
            raise RuntimeError("Direct-share receipt must match exactly one conversation input")
        message = local("GET", f"/agents/{agent}/messages/{urllib.parse.quote(message_id, safe='')}")
        if (message.get("id") != message_id or message.get("agent_id") != agent
                or message.get("body", {}).get("type") != "text"):
            raise RuntimeError("Direct-share canonical message identity does not match")
        text = message["body"]["text"]
        attachments = request.get("attachments", [])
        material = []
        if kind in ("share-text", "share-url"):
            if attachments or text != request["text"]:
                raise RuntimeError("Direct-share canonical text differs from the native request")
        else:
            attachment_kind = kind.removeprefix("share-")
            if len(attachments) != 1 or attachments[0]["kind"] != attachment_kind:
                raise RuntimeError("Direct-share attachment does not match its request kind")
            prefix = request["text"]
            if prefix and not prefix.endswith("\n"):
                prefix += "\n"
            prefix += "\n"
            link = re.fullmatch(r"(!?)\[[^\]\n]*\]\(([^)\n]+)\)", text.removeprefix(prefix))
            if not text.startswith(prefix) or not link or bool(link[1]) != (attachment_kind == "image"):
                raise RuntimeError("Direct-share canonical input lacks its attachment link")
            path = pathlib.Path(urllib.parse.unquote(link[2])).resolve(strict=True)
            inbox = (workspace / "media" / "inbox").resolve(strict=True)
            if not path.is_relative_to(inbox) or not path.name.startswith("request-"):
                raise RuntimeError("Direct-share attachment path is outside the real daemon inbox")
            data = path.read_bytes()
            if data != base64.b64decode(attachments[0]["data_base64"], validate=True):
                raise RuntimeError("Direct-share linked attachment differs from the native request bytes")
            item = {"kind": attachment_kind, "path": str(path.relative_to(root)),
                    "size": len(data), "sha256": hashlib.sha256(data).hexdigest()}
            if any(previous["path"] == item["path"] for previous in files):
                raise RuntimeError("Direct-share kinds must not reuse an attachment path")
            material.append(item)
            files.append(item)
        chains.append({"kind": kind, "client_request_id": request["client_request_id"],
                       "message_id": message_id, "input": matching[0],
                       "message": {"id": message["id"], "agent_id": message["agent_id"], "body": message["body"]},
                       "attachments": material})
    return {"source": "real daemon request/receipt/conversation/message and linked attachment bytes",
            "chains": chains, "inputs": [chain["input"] for chain in chains],
            "prompts": prompts, "files": files}


def content_report_snapshot(report_db, evidence, method, phase):
    """Export the actual table, never a synthetic receipt or the auth-containing DB."""
    with sqlite3.connect(report_db.as_uri() + "?mode=ro", uri=True) as database:
        database.row_factory = sqlite3.Row
        cursor = database.execute("SELECT * FROM content_reports ORDER BY report_id")
        columns = [field[0] for field in cursor.description]
        rows = [dict(row) for row in cursor.fetchall()]
        schema = database.execute(
            "SELECT sql FROM sqlite_master WHERE type='table' AND name='content_reports'").fetchone()[0]
    if evidence is not None:
        evidence.mkdir(mode=0o700, exist_ok=True)
        name = f"content-reports-{method}-{phase}.sqlite"
        target = evidence / name
        with os.fdopen(os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "wb"):
            pass
        with sqlite3.connect(target) as snapshot:
            snapshot.execute(schema)
            snapshot.executemany(
                "INSERT INTO content_reports VALUES (" + ",".join("?" for _ in columns) + ")",
                [tuple(row[column] for column in columns) for row in rows])
        write_fixture_json(evidence, f"content-reports-{method}-{phase}.json", {
            "source": "real daemon content_reports-only table export (not a full database backup)",
            "case": method, "phase": phase, "columns": columns, "row_count": len(rows), "rows": rows,
            "sqlite": {"path": name, "sha256": hashlib.sha256(target.read_bytes()).hexdigest()}})
    return rows


