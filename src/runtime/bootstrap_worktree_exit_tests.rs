fn git(path: &Path, args: &[&str]) -> Result<String> {
    let output = std::process::Command::new("git")
        .arg("-C")
        .arg(path)
        .args(args)
        .output()?;
    anyhow::ensure!(
        output.status.success(),
        "bootstrap fixture Git: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    Ok(String::from_utf8(output.stdout)?.trim().into())
}
async fn fixture(
    stopped: bool,
) -> Result<(
    tempfile::TempDir,
    RuntimeHandle,
    ManagedWorktreeSeed,
    TaskRecord,
)> {
    let home = tempdir()?;
    let repo = home.path().join("bootstrap-original-repository");
    std::fs::create_dir(&repo)?;
    git(&repo, &["init", "-b", "main"])?;
    git(&repo, &["config", "user.name", "Bootstrap Fixture"])?;
    git(&repo, &["config", "user.email", "bootstrap@localhost"])?;
    std::fs::write(repo.join("tracked"), "original\n")?;
    git(&repo, &["add", "tracked"])?;
    git(&repo, &["commit", "-m", "original"])?;
    let runtime = RuntimeHandle::new_isolated_resource_fixture(
        "bootstrap-child-owner",
        home.path().into(),
        context_config(),
    )?;
    runtime.refresh_context_resources().await?;
    let workspace = WorkspaceEntry::new("bootstrap-original-workspace", repo, None);
    runtime.attach_workspace(&workspace).await?;
    runtime
        .enter_workspace(
            &workspace,
            WorkspaceProjectionKind::CanonicalRoot,
            WorkspaceAccessMode::SharedRead,
            None,
            None,
        )
        .await?;
    let seed = runtime
        .prepare_managed_worktree("bootstrap-original-child")
        .await?;
    // The Task creation parent is original qualified Turn evidence, not the
    // later synthetic Result turn generated by bootstrap interruption.
    let parent_turn_id = crate::ids::turn_id();
    persist_completed_task_parent_fixture(&runtime, &parent_turn_id, None).await?;
    let at = runtime.now();
    let id = crate::ids::task_id();
    let task = TaskRecord {
        id: id.clone(),
        agent_id: runtime.instance_agent_id().into(),
        kind: TaskKind::WorktreeSubagentTask,
        status: TaskStatus::Running,
        created_at: at,
        updated_at: at,
        parent_message_id: None,
        work_item_id: None,
        summary: Some("original bootstrap child".into()),
        detail: Some(
            serde_json::json!({"workspace_mode":"worktree","parent_turn_id":parent_turn_id,"rejoin_obligation_id":id,"rejoin_generation":1,
            "worktree":{"worktree_path":seed.worktree_path,"worktree_branch":seed.worktree_branch,"original_cwd":seed.original_cwd,"original_branch":seed.original_branch},"custom":"preserved"}),
        ),
        recovery: None,
    };
    runtime
        .persist_task_transition(&task, "bootstrap_original_child_actual_ack")
        .await?;
    if stopped {
        let mut owner = runtime.begin_mutation().await?;
        owner.state.status = AgentStatus::Stopped;
        owner.persist_state(&runtime.inner.storage).await?;
        drop(owner);
    }
    runtime
        .quiesce_context_resource_observer_task_for_test()
        .await?;
    runtime.refresh_context_resources().await?;
    Ok((home, runtime, seed, task))
}
fn persisted(runtime: &RuntimeHandle, id: &str) -> Result<TaskRecord> {
    runtime
        .runtime_db()
        .tasks()
        .latest(id)?
        .context("original Task disappeared")
}
fn assert_retained(
    runtime: &RuntimeHandle,
    before: &TaskRecord,
    seed: &ManagedWorktreeSeed,
) -> Result<TaskRecord> {
    let task = persisted(runtime, &before.id)?;
    assert_eq!(task.id, before.id);
    assert_eq!(task.agent_id, before.agent_id);
    assert_eq!(task.created_at, before.created_at);
    assert_eq!(task.recovery, before.recovery);
    assert_eq!(task.status, TaskStatus::Interrupted);
    let root = runtime
        .inner
        .mutation_owner
        .capture()?
        .context("Interrupted ACK lost published root")?;
    let selected = root
        .tasks
        .as_ref()
        .context("Interrupted ACK lost Task domain")?
        .capture(&super::super::resident_task::TaskCaptureRequest {
            include_active: false,
            include_unsettled: false,
            terminal_limit: 0,
            required_keys: BTreeSet::from([super::super::resident_task::TaskKey::new(
                super::super::resident_task::TaskFamily::Task,
                &task.id,
            )]),
        })?;
    let key = super::super::resident_task::TaskKey::new(
        super::super::resident_task::TaskFamily::Task,
        &task.id,
    );
    let row = selected
        .lookup(&key)?
        .context("Interrupted ACK omitted actual Task")?;
    let super::super::resident_task::CanonicalTaskFact::Task(published) = &row.fact else {
        bail!("Interrupted ACK changed Task family");
    };
    assert_eq!(published, &task);
    assert!(
        root.current_reads.is_some(),
        "Interrupted ACK must preserve coherent Current domain"
    );
    let detail = task.detail.as_ref().unwrap();
    assert_eq!(detail["custom"], "preserved");
    assert_eq!(detail["interrupted_reason"], "agent_stopped");
    assert_eq!(
        detail["worktree"]["worktree_path"],
        serde_json::json!(seed.worktree_path)
    );
    assert_eq!(detail["worktree"]["worktree_branch"], seed.worktree_branch);
    assert_eq!(detail["worktree"]["cleanup_status"], "retained");
    assert_eq!(
        detail["worktree"]["cleanup_reason"],
        "original_child_exit_unproven"
    );
    assert_eq!(detail["worktree"]["retained_for_review"], true);
    assert!(detail["worktree"].get("auto_cleaned_up").is_none());
    let id = task
        .parent_message_id
        .as_deref()
        .context("Interrupted ACK lost original Result")?;
    let result = runtime
        .storage()
        .read_message_by_id(id)?
        .context("Interrupted ACK lost Result body")?;
    assert_eq!(result.kind, MessageKind::TaskResult);
    let mut frozen_detail = detail.clone();
    if before
        .detail
        .as_ref()
        .and_then(|detail| detail.get(PARENT_TURN_ID_DETAIL))
        .is_none()
    {
        let original_turn = result
            .turn_id
            .as_ref()
            .context("original Result turn missing")?;
        assert_eq!(
            frozen_detail
                .as_object_mut()
                .unwrap()
                .remove(PARENT_TURN_ID_DETAIL),
            Some(serde_json::json!(original_turn)),
            "only task_with_result_message may add its exact original Result turn"
        );
    }
    assert_eq!(
        result.metadata.as_ref().unwrap()["task_detail"],
        frozen_detail
    );
    assert_eq!(
        result.metadata.as_ref().unwrap()["interrupted_reason"],
        "agent_stopped"
    );
    assert_eq!(
        runtime
            .runtime_db()
            .queue_entries()
            .latest(id)?
            .unwrap()
            .status,
        QueueEntryStatus::Queued
    );
    assert_eq!(runtime.runtime_db().connection()?.query_row("SELECT COUNT(*) FROM audit_events WHERE kind IN ('worktree_auto_cleaned_up','task_worktree_cleanup_already_removed')", [], |r|r.get::<_,usize>(0))?, 0);
    Ok(task)
}
fn business_counts(runtime: &RuntimeHandle) -> Result<(usize, usize, usize, usize)> {
    Ok(runtime.runtime_db().connection()?.query_row("SELECT (SELECT COUNT(*) FROM messages),(SELECT COUNT(*) FROM queue_entries),(SELECT COUNT(*) FROM audit_events),(SELECT COUNT(*) FROM input_mutation_receipts)", [], |r|Ok((r.get(0)?,r.get(1)?,r.get(2)?,r.get(3)?)))?)
}
#[tokio::test]
async fn stopped_bootstrap_uses_actual_qualified_cut_and_retains_clean_worktree_without_child_exit(
) -> Result<()> {
    let (home, runtime, seed, task) = fixture(true).await?;
    let agent = runtime.instance_agent_id().to_owned();
    assert!(runtime
        .inner
        .runtime_db
        .pending_control_obligations(&agent, runtime.instance_incarnation())?
        .is_empty());
    drop(runtime);
    let runtime =
        RuntimeHandle::new_isolated_resource_fixture(&agent, home.path().into(), context_config())?;
    runtime
        .quiesce_context_resource_observer_task_for_test()
        .await?;
    assert_eq!(runtime.agent_state().await?.status, AgentStatus::Stopped);
    assert!(
        runtime.inner.recovered_tasks.lock().await.is_some(),
        "constructor must retain the actual active Task source"
    );
    // This is the actual run_inner ordering, with no invented Control receipt.
    runtime.reconcile_loaded_control_obligations().await?;
    runtime.bootstrap_recovery().await?;
    let terminal = assert_retained(&runtime, &task, &seed)?;
    assert!(seed.worktree_path.exists());
    assert!(git(&seed.worktree_path, &["status", "--porcelain"])?.is_empty());
    assert_eq!(
        git(&seed.worktree_path, &["branch", "--show-current"])?,
        seed.worktree_branch
    );
    git(
        &seed.original_cwd,
        &[
            "show-ref",
            "--verify",
            &format!("refs/heads/{}", seed.worktree_branch),
        ],
    )?;
    let before = business_counts(&runtime)?;
    runtime.bootstrap_recovery().await?;
    assert_eq!(business_counts(&runtime)?, before);
    assert_eq!(persisted(&runtime, &task.id)?, terminal);
    runtime
        .quiesce_context_resource_observer_task_for_test()
        .await?;
    drop(runtime);
    let runtime =
        RuntimeHandle::new_isolated_resource_fixture(&agent, home.path().into(), context_config())?;
    runtime
        .quiesce_context_resource_observer_task_for_test()
        .await?;
    runtime.bootstrap_recovery().await?;
    assert_eq!(persisted(&runtime, &task.id)?, terminal);
    assert_eq!(business_counts(&runtime)?, before);
    assert!(seed.worktree_path.exists());
    Ok(())
}
#[tokio::test]
async fn stopped_bootstrap_parent_monitor_cancel_and_join_do_not_prove_independent_child_exit(
) -> Result<()> {
    let (_home, runtime, seed, task) = fixture(false).await?;
    let registration = runtime
        .admit_control_task_handle_registration(&task)
        .await?;
    let lease = runtime.inner.control_cancellations.task(&task);
    lease.attach(tokio::spawn(std::future::pending::<()>()));
    runtime.inner.task_handles.lock().await.insert(
        task.id.clone(),
        command_task::ManagedTaskHandle::Async(
            super::super::control_cancellation::SharedControlTaskHandle(lease.clone()),
        ),
    );
    drop(registration);
    let (exit, physical_exit) = tokio::sync::oneshot::channel::<()>();
    let (started, physical_started) = tokio::sync::oneshot::channel::<()>();
    // A real independent worker remains live while its parent observer exits.
    // It is deliberately not an opaque Host physical-exit capability.
    let path = seed.worktree_path.clone();
    let physical = tokio::spawn(async move {
        let _ = started.send(());
        let _ = physical_exit.await;
        path.exists()
    });
    physical_started.await?;
    // The original real registration is admitted before administrative Stop.
    let mut owner = runtime.begin_mutation().await?;
    owner.state.status = AgentStatus::Stopped;
    owner.persist_state(&runtime.inner.storage).await?;
    drop(owner);
    runtime.refresh_context_resources().await?;
    runtime
        .interrupt_active_tasks_for_lifecycle_stop(vec![task.clone()])
        .await?;
    assert_retained(&runtime, &task, &seed)?;
    tokio::time::timeout(Duration::from_secs(5), lease.join()).await??;
    assert!(
        !physical.is_finished(),
        "parent join must not be equated with child physical exit"
    );
    assert!(seed.worktree_path.exists());
    git(
        &seed.original_cwd,
        &[
            "show-ref",
            "--verify",
            &format!("refs/heads/{}", seed.worktree_branch),
        ],
    )?;
    exit.send(())
        .map_err(|_| anyhow!("physical worker exited early"))?;
    assert!(physical.await?);
    Ok(())
}
#[tokio::test]
async fn stopped_bootstrap_retained_task_and_result_keep_whole_rollback_and_known_ack() -> Result<()>
{
    for fault in [
        TransitionFaultPoint::BeforeCommit,
        TransitionFaultPoint::BeforeCacheUpdate,
    ] {
        let (_home, runtime, seed, task) = fixture(true).await?;
        let before = business_counts(&runtime)?;
        runtime.inject_next_transition_fault(fault);
        let error = runtime
            .interrupt_active_tasks_for_lifecycle_stop(vec![task.clone()])
            .await
            .err()
            .context("actual injected Task commit must fail")?;
        assert!(
            seed.worktree_path.exists(),
            "neither SQL fault can authorize physical removal"
        );
        git(
            &seed.original_cwd,
            &[
                "show-ref",
                "--verify",
                &format!("refs/heads/{}", seed.worktree_branch),
            ],
        )?;
        if fault == TransitionFaultPoint::BeforeCommit {
            assert!(format!("{error:#}").contains("BeforeCommit"));
            assert_eq!(persisted(&runtime, &task.id)?, task);
            assert_eq!(business_counts(&runtime)?, before);
            runtime
                .interrupt_active_tasks_for_lifecycle_stop(vec![task.clone()])
                .await?;
        } else {
            assert!(
                runtime.inner.mutation_owner.capture().is_err(),
                "Known must keep ordinary projection gated"
            );
            let owner = runtime.begin_mutation().await?;
            drop(owner);
        }
        assert_retained(&runtime, &task, &seed)?;
        assert!(seed.worktree_path.exists());
    }
    Ok(())
}
#[tokio::test]
async fn stopped_bootstrap_does_not_infer_removal_from_missing_path_or_rewrite_other_task_metadata(
) -> Result<()> {
    let (_home, runtime, seed, task) = fixture(true).await?;
    git(
        &seed.original_cwd,
        &["worktree", "remove", seed.worktree_path.to_str().unwrap()],
    )?;
    assert!(!seed.worktree_path.exists());
    runtime
        .interrupt_active_tasks_for_lifecycle_stop(vec![task.clone()])
        .await?;
    assert_retained(&runtime, &task, &seed)?;
    git(
        &seed.original_cwd,
        &[
            "show-ref",
            "--verify",
            &format!("refs/heads/{}", seed.worktree_branch),
        ],
    )?;
    let mut other = task.clone();
    other.id = crate::ids::task_id();
    other.kind = TaskKind::CommandTask;
    other.detail = Some(
        serde_json::json!({"worktree":{"worktree_path":seed.worktree_path,"worktree_branch":seed.worktree_branch},"custom":"non-child"}),
    );
    runtime
        .persist_task_transition(&other, "bootstrap_other_actual_ack")
        .await?;
    runtime
        .interrupt_active_tasks_for_lifecycle_stop(vec![other.clone()])
        .await?;
    let actual = persisted(&runtime, &other.id)?;
    assert_eq!(actual.status, TaskStatus::Interrupted);
    assert_eq!(
        actual.detail.as_ref().unwrap()["worktree"],
        other.detail.as_ref().unwrap()["worktree"]
    );
    assert_eq!(actual.detail.as_ref().unwrap()["custom"], "non-child");
    Ok(())
}

