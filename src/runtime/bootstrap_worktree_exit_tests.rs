        assert_eq!(terminal.status, TaskStatus::Interrupted);
        assert_eq!(terminal.created_at, original.created_at);
        assert_eq!(unbound_task_rejoin_generation(&terminal), Some(1));
        assert!(terminal.rejoin_fence().is_err());
